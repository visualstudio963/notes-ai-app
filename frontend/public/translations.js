/**
 * Infer chat reply locale from user text (Albanian vs English). Not UI language — used for Web Chat bot copy only.
 * @param {string} text
 * @returns {"sq"|"en"}
 */
function inferWebChatMessageLang(text) {
  const s = String(text || "").trim();
  if (!s) return "en";
  if (/[çëÇË]/.test(s)) return "sq";
  const sqWord =
    /\b(pershendetje|persh[eë]ndetje|p[eë]rsh|tung|tungjatjeta|faleminderit|flm|mir[eë]mbr[eë]ma|m[eë]rzitur|d[eë]shir|ju\s+faleminderit|me\s+kujto|m[eë]\s+kujto|kujto|neser|nes[eë]r|pasneser|pasnes[eë]r|pasdite|pas\s+dite|m[eë]ngjes|oren|or[eë]n|sot|shqipë|shqip|cfare|çfare|cfar[eë]|si\s+jeni|si\s+je)\b/i;
  if (sqWord.test(s)) return "sq";
  const enWord =
    /\b(hello|hi\b|hey\b|thanks|thank\s+you|remind\s+me|please\b|good\s+morning|tomorrow\b|today\b|afternoon|evening)\b/i;
  if (enWord.test(s)) return "en";
  return "en";
}

/**
 * Resolve a translation key for an explicit locale (sq | en), same merge rules as {@link t}.
 * @param {string} key
 * @param {"sq"|"en"|string} langCode
 */
function tForLang(key, langCode) {
  const code = translations[langCode] ? langCode : "en";
  const en = translations.en || {};
  if (code === "en") {
    const v = en[key];
    return v !== undefined && v !== null && v !== "" ? v : key;
  }
  const overlay = translations[code] || {};
  const v = overlay[key];
  if (v !== undefined && v !== null && v !== "") return v;
  const fallback = en[key];
  return fallback !== undefined && fallback !== null && fallback !== "" ? fallback : key;
}

// Get current language or default to English (fixes invalid / stale codes in localStorage)
function getCurrentLanguage() {
  const raw = localStorage.getItem("language") || "en";
  if (!translations[raw]) {
    localStorage.setItem("language", "en");
    resetTranslationDictCache();
    return "en";
  }
  return raw;
}

let __translationDictCache = null;
let __translationDictLang = null;

function resetTranslationDictCache() {
  __translationDictCache = null;
  __translationDictLang = null;
}

/** Merged dictionary: English base + locale overlay so partial locales never show raw keys. */
function getTranslationDictionary() {
  const lang = getCurrentLanguage();
  if (__translationDictCache && __translationDictLang === lang) {
    return __translationDictCache;
  }
  const en = translations.en || {};
  const overlay = translations[lang];
  __translationDictLang = lang;
  if (!overlay || lang === "en") {
    __translationDictCache = en;
  } else {
    const merged = { ...en };
    for (const k of Object.keys(overlay)) {
      const v = overlay[k];
      if (v !== undefined && v !== null && v !== "") merged[k] = v;
    }
    __translationDictCache = merged;
  }
  return __translationDictCache;
}

// Get translated text
function t(key) {
  const dict = getTranslationDictionary();
  const v = dict[key];
  if (v !== undefined && v !== null && v !== "") return v;
  const fallback = translations.en && translations.en[key];
  return fallback !== undefined && fallback !== null && fallback !== "" ? fallback : key;
}

// Set language
function setLanguage(lang) {
  if (translations[lang]) {
    localStorage.setItem('language', lang);
    resetTranslationDictCache();
    applyTranslations();
  }
}

// Apply translations to the page
function applyTranslations() {
  document.querySelectorAll("[data-t]").forEach((el) => {
    const key = el.getAttribute("data-t");
    if (!key) return;
    try {
      el.textContent = t(key);
    } catch (e) {
      console.warn("applyTranslations data-t:", key, e);
    }
  });

  document.querySelectorAll("[data-t-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-t-placeholder");
    if (!key) return;
    try {
      el.placeholder = t(key);
    } catch (e) {
      console.warn("applyTranslations placeholder:", key, e);
    }
  });

  document.querySelectorAll("[data-t-title]").forEach((el) => {
    const key = el.getAttribute("data-t-title");
    if (!key) return;
    try {
      el.title = t(key);
    } catch (e) {
      console.warn("applyTranslations title:", key, e);
    }
  });

  document.querySelectorAll("[data-t-aria-label]").forEach((el) => {
    const key = el.getAttribute("data-t-aria-label");
    if (!key) return;
    try {
      el.setAttribute("aria-label", t(key));
    } catch (e) {
      console.warn("applyTranslations aria-label:", key, e);
    }
  });

  if (typeof syncOfflineIndicatorUi === "function") {
    syncOfflineIndicatorUi();
  }
  if (typeof syncWebChatModelSelectorUi === "function") {
    syncWebChatModelSelectorUi();
  }
  if (typeof syncPremiumGatedNav === "function") {
    syncPremiumGatedNav();
  }
  if (typeof webChatRenderRecentCommands === "function") {
    webChatRenderRecentCommands();
  }
  if (typeof applyDiscordCommunityUi === "function") {
    applyDiscordCommunityUi();
  }
  if (typeof syncCategoryDependentUi === "function") {
    syncCategoryDependentUi();
  }
}
